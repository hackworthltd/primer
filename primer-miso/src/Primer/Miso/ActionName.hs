-- | Short labels for action buttons, as used by the old TypeScript frontend.
module Primer.Miso.ActionName (actionName) where

import Foreword

import Primer.Action.Available (Action (..), InputAction (..), NoInputAction (..))

actionName :: Action -> Text
actionName = \case
  NoInput a -> case a of
    MakeCase -> "m"
    MakeApp -> "$"
    MakeAPP -> "@"
    MakeAnn -> ":"
    RemoveAnn -> "⌫:"
    LetToRec -> "rec"
    Raise -> "↑"
    EnterHole -> "h"
    RemoveHole -> "e"
    DeleteExpr -> "⌫"
    MakeFun -> "→"
    AddInput -> "→A→"
    MakeTApp -> "$"
    RaiseType -> "↑"
    DeleteType -> "⌫"
    DuplicateDef -> "d"
    DeleteDef -> "⌫"
    DeleteTypeDef -> "⌫"
    DeleteCon -> "⌫"
    AddConField -> "+"
    DeleteConField -> "p⌫"
    DeleteTypeParam -> "⌫"
    MakeKType -> "*"
    MakeKFun -> "→"
    DeleteKind -> "⌫"
  Input a -> case a of
    MakeCon -> "V ? ?"
    MakeInt -> "1"
    MakeDouble -> "1.0"
    MakeChar -> "\"c\""
    MakeVar -> "x"
    MakeVarSat -> "f $ ?"
    MakeLet -> "="
    MakeLetRec -> "=,="
    MakeLam -> "λx"
    MakeLAM -> "Λx"
    AddBranch -> "＋"
    AddBranchInt -> "＋"
    AddBranchChar -> "＋"
    DeleteBranch -> "－"
    DeleteBranchInt -> "－"
    DeleteBranchChar -> "－"
    RenameBinding -> "r"
    MakeTCon -> "T"
    MakeTVar -> "t"
    MakeForall -> "∀"
    RenameDef -> "r"
    RenameType -> "r"
    RenameCon -> "r"
    RenameTypeParam -> "r"
    AddCon -> "+"
    AddTypeParam -> "t"
